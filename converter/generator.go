// wasmParamType returns the WASM value type of the i-th declared parameter.
func (tf templateFuncs) wasmParamType(m Method, i int) (ValueType, bool) {
	if m.Wasm == nil || i >= len(m.Wasm.Params) {
		return ValI32, false
	}
	return m.Wasm.Params[i], true
}

// marshalParam returns setup code and the WASM argument expression for one input
// parameter.
func (tf templateFuncs) marshalParam(m Method, name string, idx int, t TSType, zeroRet string) (setup string, wasmArg string) {
	wt, haveWT := tf.wasmParamType(m, idx)
	switch t.Kind {
	case KindNumber:
		if haveWT && wt == ValF32 {
			return "", fmt.Sprintf("f32(%s)", name)
		}
		if haveWT && wt == ValI64 {
			return "", fmt.Sprintf("uint64(%s)", name)
		}
		// integer / pointer-count argument
		return "", fmt.Sprintf("uint64(uint32(%s))", name)
	case KindBoolean:
		bv := fmt.Sprintf("_p%dB", idx)
		s := fmt.Sprintf("\n\tvar %s uint64\n\tif %s { %s = 1 }", bv, name, bv)
		return s, bv
	case KindEnum:
		return "", fmt.Sprintf("uint64(%s)", name)
	case KindBigInt:
		return "", fmt.Sprintf("uint64(%s)", name)
	case KindTupleAlias:
		if tf.isHandleType(t) {
			return "", fmt.Sprintf("%s[0]", name)
		}
		c, ok := tf.codecFor(t.Raw)
		if !ok || c.writer == "" {
			return "", "0 /* TODO: unsupported composite parameter */"
		}
		ptr := fmt.Sprintf("_p%dPtr", idx)
		setup := fmt.Sprintf(
			"\n\t%s, err := h.Alloc(ctx, %s%s)\n\tif err != nil { return %s, err }\n\tdefer h.FreePtr(ctx, %s)\n\tif err := %s%s(h.Mem(), %s, %s); err != nil { return %s, err }",
			ptr, tf.typePrefix, c.sizeConst, zeroRet, ptr, tf.typePrefix, c.writer, ptr, name, zeroRet)
		return setup, fmt.Sprintf("uint64(%s)", ptr)
	}
	return "", "0 /* unknown parameter kind */"
}

// outSize returns the Go expression for the out-buffer size of one return element.
func (tf templateFuncs) outSize(el TSType) string {
	switch el.Kind {
	case KindNumber, KindEnum, KindBoolean:
		return "4"
	case KindBigInt:
		return "8"
	case KindTupleAlias:
		if tf.isHandleType(el) {
			return "8"
		}
		if c, ok := tf.codecFor(el.Raw); ok {
			return tf.typePrefix + c.sizeConst
		}
		return fmt.Sprintf("%d", tf.schema.AllocSizeOf(el))
	}
	return "8"
}

// outRead returns (statements, expression) to deserialise one return element
// from its out-buffer pointer.
func (tf templateFuncs) outRead(m Method, el TSType, idx int, ptr, zeroRet string) (string, string) {
	varName := fmt.Sprintf("_r%d", idx)
	switch el.Kind {
	case KindNumber:
		if f32NumberReturners[m.Name] {
			return fmt.Sprintf("\n\t%s, err := %sReadF32(h.Mem(), %s)\n\tif err != nil { return %s, err }", varName, tf.typePrefix, ptr, zeroRet),
				fmt.Sprintf("float64(%s)", varName)
		}
		return fmt.Sprintf("\n\t%s, err := %sReadI32(h.Mem(), %s)\n\tif err != nil { return %s, err }", varName, tf.typePrefix, ptr, zeroRet),
			fmt.Sprintf("float64(%s)", varName)
	case KindEnum:
		return fmt.Sprintf("\n\t%s, err := %sReadI32(h.Mem(), %s)\n\tif err != nil { return %s, err }", varName, tf.typePrefix, ptr, zeroRet),
			fmt.Sprintf("%s%s(%s)", tf.typePrefix, el.Raw, varName)
	case KindBoolean:
		return fmt.Sprintf("\n\t%s, err := %sReadI32(h.Mem(), %s)\n\tif err != nil { return %s, err }", varName, tf.typePrefix, ptr, zeroRet),
			fmt.Sprintf("%s != 0", varName)
	case KindBigInt:
		return fmt.Sprintf("\n\t%s, err := %sReadU64(h.Mem(), %s)\n\tif err != nil { return %s, err }", varName, tf.typePrefix, ptr, zeroRet),
			varName
	case KindTupleAlias:
		if tf.isHandleType(el) {
			return fmt.Sprintf("\n\t%s, err := %sReadU64(h.Mem(), %s)\n\tif err != nil { return %s, err }", varName, tf.typePrefix, ptr, zeroRet),
				fmt.Sprintf("%s%s{%s}", tf.typePrefix, el.Raw, varName)
		}
		if c, ok := tf.codecFor(el.Raw); ok && c.reader != "" {
			return fmt.Sprintf("\n\t%s, err := %s%s(h.Mem(), %s)\n\tif err != nil { return %s, err }", varName, tf.typePrefix, c.reader, ptr, zeroRet),
				varName
		}
		return fmt.Sprintf("\n\t// TODO: no codec for return type %s\n\t_ = %s", el.Raw, ptr), fmt.Sprintf("%s%s{}", tf.typePrefix, el.Raw)
	}
	return "", "nil"
}

// FuncBody generates the complete function body for a given method.
func (tf templateFuncs) FuncBody(m Method) string {
	var b strings.Builder

	zeroRet := tf.zeroExpr(m.ReturnType)
	isTuple := len(m.ReturnType.Elements) > 0

	// Return tuple = [Result, data...]; data elements each get their own out-pointer.
	var dataElems []TSType
	if isTuple && len(m.ReturnType.Elements) > 1 {
		dataElems = m.ReturnType.Elements[1:]
	}

	// 1. Allocate one out-buffer per data element.
	outPtrs := make([]string, len(dataElems))
	for i, el := range dataElems {
		ptr := fmt.Sprintf("_out%d", i)
		outPtrs[i] = ptr
		b.WriteString(fmt.Sprintf(
			"\n\t%s, err := h.Alloc(ctx, %s)\n\tif err != nil { return %s, err }\n\tdefer h.FreePtr(ctx, %s)",
			ptr, tf.outSize(el), zeroRet, ptr))
	}

	// 2. Marshal input parameters.
	var wasmArgs []string
	for i, p := range m.Params {
		setup, arg := tf.marshalParam(m, p.Name, i, p.TSType, zeroRet)
		if setup != "" {
			b.WriteString(setup)
		}
		wasmArgs = append(wasmArgs, arg)
	}

	// 3. Out-pointers go LAST.
	for _, ptr := range outPtrs {
		wasmArgs = append(wasmArgs, fmt.Sprintf("uint64(%s)", ptr))
	}

	argsStr := ""
	if len(wasmArgs) > 0 {
		argsStr = ", " + strings.Join(wasmArgs, ", ")
	}

	wasmName := m.WasmName
	if wasmName == "" {
		wasmName = m.Name
	}

	// 4. Call the WASM export.
	if !isTuple {
		if m.ReturnType.Kind == KindEnum || m.ReturnType.Kind == KindVoid || m.ReturnType.Raw == "" {
			b.WriteString(fmt.Sprintf("\n\treturn h.CallResultI32(ctx, %q%s)", wasmName, argsStr))
			return b.String()
		}
		// Scalar non-enum return (number / boolean): decode the raw i32.
		b.WriteString(fmt.Sprintf("\n\tfn := h.Module().ExportedFunction(%q)", wasmName))
		b.WriteString(fmt.Sprintf("\n\tif fn == nil { return %s, fmt.Errorf(\"havok: %%s not exported\", %q) }", zeroRet, wasmName))
		b.WriteString(fmt.Sprintf("\n\t_res, callErr := fn.Call(ctx%s)\n\tif callErr != nil { return %s, fmt.Errorf(\"havok: %%s: %%w\", %q, callErr) }", argsStr, zeroRet, wasmName))
		switch m.ReturnType.Kind {
		case KindNumber:
			b.WriteString("\n\treturn float64(uint32(_res[0])), nil")
		case KindBoolean:
			b.WriteString("\n\treturn _res[0] != 0, nil")
		default:
			b.WriteString(fmt.Sprintf("\n\treturn %s, nil", zeroRet))
		}
		return b.String()
	}

	b.WriteString(fmt.Sprintf("\n\tfn := h.Module().ExportedFunction(%q)", wasmName))
	b.WriteString(fmt.Sprintf("\n\tif fn == nil { return %s, fmt.Errorf(\"havok: %%s not exported\", %q) }", zeroRet, wasmName))
	b.WriteString(fmt.Sprintf("\n\t_res, callErr := fn.Call(ctx%s)\n\tif callErr != nil { return %s, fmt.Errorf(\"havok: %%s: %%w\", %q, callErr) }", argsStr, zeroRet, wasmName))

	// 5. Deserialise each data element from its out-buffer.
	var exprs []string
	for i, el := range dataElems {
		stmts, expr := tf.outRead(m, el, i, outPtrs[i], zeroRet)
		b.WriteString(stmts)
		exprs = append(exprs, expr)
	}
	if len(exprs) == 0 {
		b.WriteString(fmt.Sprintf("\n\treturn %sResult(int32(_res[0])), nil", tf.typePrefix))
		return b.String()
	}
	b.WriteString(fmt.Sprintf("\n\treturn %sResult(int32(_res[0])), %s, nil", tf.typePrefix, strings.Join(exprs, ", ")))
	return b.String()
}

// zeroExpr returns the Go source for the zero value of t.
func (tf templateFuncs) zeroExpr(t TSType) string {
	if len(t.Elements) > 0 {
		var parts []string
		for _, el := range t.Elements {
			parts = append(parts, tf.scalarZero(el))
		}
		return strings.Join(parts, ", ")
	}
	return tf.scalarZero(t)
}

func (tf templateFuncs) scalarZero(t TSType) string {
	switch t.Kind {
	case KindVoid:
		return ""
	case KindNumber, KindBigInt, KindEnum:
		return "0"
	case KindBoolean:
		return "false"
	case KindTupleAlias:
		gt := tf.QualifiedGoType(t)
		if gt == "" || gt == "interface{}" {
			return "nil"
		}
		return gt + "{}"
	}
	return "nil"
}

// normalizeName strips underscores and lower-cases, so that d.ts spellings such
// as HP_Shape_PathIterator_GetNext match the wasm export HP_ShapePathIterator_GetNext.
func normalizeName(s string) string {
	return strings.ToLower(strings.ReplaceAll(s, "_", ""))
}

func generateBindings(schema *Schema, wasm WasmSignatures, opts GenerateOptions) error {
	// Build a normalised index of wasm exports for tolerant name matching.
	norm := make(map[string]string, len(wasm))
	for name := range wasm {
		norm[normalizeName(name)] = name
	}

	var methods []Method
	var skipped []string
	for _, m := range schema.Methods {
		wasmName, ok := "", false
		if _, ok = wasm[m.Name]; ok {
			wasmName = m.Name
		} else if alt, found := norm[normalizeName(m.Name)]; found {
			wasmName = alt
			ok = true
		} else {
			ok = false
		}
		if !ok {
			skipped = append(skipped, m.Name)
			continue
		}
		sig := wasm[wasmName]
		if !sig.ReturnsI32() {
			skipped = append(skipped, m.Name+" (unexpected wasm return type)")
			continue
		}
		m.WasmName = wasmName
		m.Wasm = &sig
		methods = append(methods, m)
	}

	slices.SortFunc(methods, func(a, b Method) int { return cmp.Compare(a.Name, b.Name) })
	slices.Sort(skipped)

	fmt.Printf("Bindings: %d methods matched against wasm exports\n", len(methods))
	if len(skipped) > 0 {
		fmt.Printf("Skipped %d method(s) not exported by this HavokPhysics.wasm:\n", len(skipped))
		for _, s := range skipped {
			fmt.Printf("  - %s\n", s)
		}
	}

	receiverType := opts.ReceiverType
	if receiverType == "" {
		receiverType = "HP"
	}
	bindingPkg := opts.BindingPkg
	if bindingPkg == "" {
		bindingPkg = "github.com/gsw945/havok-go/havok/binding"
	}
	typePrefix := ""
	if bindingPkg != "" {
		parts := strings.Split(bindingPkg, "/")
		typePrefix = parts[len(parts)-1] + "."
	}
	tf := templateFuncs{schema: schema, wasm: wasm, typePrefix: typePrefix}

	funcMap := template.FuncMap{
		"GoType":          tf.GoType,
		"QualifiedGoType": tf.QualifiedGoType,
		"FuncReturn":      tf.FuncReturn,
		"FuncBody":        tf.FuncBody,
		"TSDoc":           tf.TSDoc,
	}

	type templateData struct {
		PackageName     string
		ReceiverType    string
		BindingPkg      string
		Methods         []Method
		GoType          func(TSType) string
		QualifiedGoType func(TSType) string
		FuncReturn      func(TSType) string
		FuncBody        func(Method) string
		TSDoc           func(string) string
	}
	data := templateData{
		PackageName:     opts.PackageName,
		ReceiverType:    receiverType,
		BindingPkg:      bindingPkg,
		Methods:         methods,
		GoType:          tf.GoType,
		QualifiedGoType: tf.QualifiedGoType,
		FuncReturn:      tf.FuncReturn,
		FuncBody:        tf.FuncBody,
		TSDoc:           tf.TSDoc,
	}

	tmpl, err := template.New("bindings").Funcs(funcMap).Parse(bindingsTemplate)
	if err != nil {
		return fmt.Errorf("converter: bindings template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("converter: render bindings: %w", err)
	}

	// gofmt the output; a parse failure here also catches malformed generated code.
	src := buf.Bytes()
	if formatted, ferr := format.Source(src); ferr == nil {
		src = formatted
	} else {
		fmt.Fprintf(os.Stderr, "converter: warning: generated bindings are not valid Go (%v); writing raw output\n", ferr)
	}

	outPath := filepath.Join(opts.OutputDir, opts.BindingFile)
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		return fmt.Errorf("converter: write %s: %w", opts.BindingFile, err)
	}
	return nil
}
